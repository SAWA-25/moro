function buildMinor(): TarotCardDef[] {
    const out: TarotCardDef[] = [];
    let idx = 22;
    for (const s of suitMeta) {
        for (const [rankCn, rankEn, up, rev] of ranks) {
            out.push({
                index: idx++,
                name: `${s.cn}${rankCn}`,
                nameEn: `${rankEn} of ${s.en}`,
                suit: s.key,
                keywords: [s.cn, rankCn],
                upright: `${s.theme}——${up}。`,
                reversed: `${rev}。`,
            });
        }
    }
    return out;
}

